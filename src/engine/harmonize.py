def commute_label(gubun, place, other_sido, minutes, home_sido):
    """통근 사실 문장. 코드집에 없는 해석(예: 41번 공란=같은 시도)은 쓰지 않는다 — 어느 쪽이든 참인 문장만.

    모든 인자는 NaN-안전 문자열('' = 결측). 통근자가 아니거나 장소를 알 수 없으면 None.
    """
    if gubun != "1" or place not in COMMUTE_PLACE:
        return None
    if place == "1":
        where = "사는 곳과 같은 읍·면·동"
    elif other_sido in SIDO_FULLNAME and other_sido != home_sido:
        where = SIDO_FULLNAME[other_sido]
    else:
        where = "사는 곳과 다른 읍·면·동"
    try:
        mins = int(float(minutes)) if minutes else 0
    except ValueError:
        mins = 0
    if mins > 0:
        return f"직장은 {where}에 있고 통근에 약 {mins}분 걸립니다."
    return f"직장은 {where}에 있습니다."
