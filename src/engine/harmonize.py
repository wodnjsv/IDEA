def edu4_census(code: str) -> str:
    """센서스 교육정도코드 1~8 (1=안받음,2=초등,3=중학,4=고등,5=2·3년제,6=4년제,7=석사,8=박사)."""
    c = int(code)
    if c <= 3:
        return "중졸이하"
    if c == 4:
        return "고졸"
    if c <= 6:
        return "전문·대졸"
    return "대학원이상"


def edu4_laf(code: str) -> str:
    """지역별고용 학력구분코드 0~7 (0=무학,1=초등,2=중학,3=고등,4=전문대,5=대학교,6=석사,7=박사)."""
    c = int(code)
    if c <= 2:
        return "중졸이하"
    if c == 3:
        return "고졸"
    if c <= 5:
        return "전문·대졸"
    return "대학원이상"


def edu4_kgss(educ: float) -> str:
    """KGSS EDUC 0~8 (0=무학..3=고교,4=전문대,5=대학교,6=석사,7=박사,8=서당한학)."""
    c = int(educ)
    if c in (0, 1, 2, 8):
        return "중졸이하"
    if c == 3:
        return "고졸"
    if c in (4, 5):
        return "전문·대졸"
    return "대학원이상"


